use std::fs;
use std::path::Path;

use anyhow::Result;
use apxm_core::events::kind::{CORE_EVENT_KINDS, EventCategory};

pub fn render_generated_event_kinds() -> String {
    let mut buf = String::new();
    buf.push_str("// AUTO-GENERATED by apxm codegen event-kinds; DO NOT EDIT.\n\n");
    buf.push_str("export type EventCategory =\n");
    for (index, category) in EventCategory::ALL.iter().enumerate() {
        let sep = if index + 1 == EventCategory::ALL.len() {
            ";"
        } else {
            ""
        };
        buf.push_str(&format!("  | {}{sep}\n", ts_string(category.as_str())));
    }
    buf.push('\n');
    buf.push_str("export interface EventKind<N extends string = string> {\n");
    buf.push_str("  readonly name: N;\n");
    buf.push_str("  readonly category: EventCategory;\n");
    buf.push_str("  readonly terminal: boolean;\n");
    buf.push_str("}\n\n");
    buf.push_str("function kind<N extends string>(\n");
    buf.push_str("  name: N,\n");
    buf.push_str("  category: EventCategory,\n");
    buf.push_str("  terminal = false,\n");
    buf.push_str("): EventKind<N> {\n");
    buf.push_str("  return { name, category, terminal };\n");
    buf.push_str("}\n\n");

    let identifiers = event_kind_identifiers();
    for event_kind in CORE_EVENT_KINDS {
        let ident = identifiers
            .iter()
            .find_map(|(name, ident)| (*name == event_kind.name()).then_some(ident.as_str()))
            .expect("event kind identifier");
        let category = ts_string(event_kind.category().as_str());
        if event_kind.is_terminal() {
            buf.push_str(&format!(
                "export const {ident} = kind({}, {category}, true);\n",
                ts_string(event_kind.name())
            ));
        } else {
            buf.push_str(&format!(
                "export const {ident} = kind({}, {category});\n",
                ts_string(event_kind.name())
            ));
        }
    }

    buf.push_str("\nexport const CORE_EVENT_KINDS = [\n");
    for event_kind in CORE_EVENT_KINDS {
        let ident = identifiers
            .iter()
            .find_map(|(name, ident)| (*name == event_kind.name()).then_some(ident.as_str()))
            .expect("event kind identifier");
        buf.push_str(&format!("  {ident},\n"));
    }
    buf.push_str("] as const;\n\n");
    buf.push_str("export type CoreEventKindName = (typeof CORE_EVENT_KINDS)[number][\"name\"];\n");

    buf
}

pub fn write_generated_event_kinds(output_path: impl AsRef<Path>) -> Result<()> {
    let output_path = output_path.as_ref();
    if let Some(parent) = output_path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(output_path, render_generated_event_kinds())?;
    Ok(())
}

fn ts_string(value: &str) -> String {
    serde_json::to_string(value).expect("serialize string")
}

fn event_kind_identifiers() -> Vec<(&'static str, String)> {
    let mut seen = std::collections::BTreeMap::<String, &'static str>::new();
    let mut identifiers = Vec::with_capacity(CORE_EVENT_KINDS.len());

    for event_kind in CORE_EVENT_KINDS {
        let name = event_kind.name();
        let ident = ts_identifier(name);
        if let Some(existing) = seen.insert(ident.clone(), name) {
            panic!(
                "event kind names `{existing}` and `{name}` both generate TypeScript identifier `{ident}`"
            );
        }
        identifiers.push((name, ident));
    }

    identifiers
}

fn ts_identifier(name: &str) -> String {
    let mut ident = String::with_capacity(name.len());
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() || ch == '_' {
            ident.push(ch.to_ascii_uppercase());
        } else {
            ident.push('_');
        }
    }

    if ident.is_empty() || ident.as_bytes()[0].is_ascii_digit() {
        ident.insert(0, '_');
    }

    ident
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn event_kinds_typescript_contains_event_category_type() {
        let output = render_generated_event_kinds();

        assert!(output.contains("export type EventCategory ="));
        assert!(output.contains("| \"observability\""));
        assert!(output.contains("| \"user_action\";"));
    }

    #[test]
    fn event_kinds_typescript_categories_come_from_rust_registry() {
        let output = render_generated_event_kinds();

        for category in EventCategory::ALL {
            assert!(output.contains(&format!("| {}", ts_string(category.as_str()))));
        }
    }

    #[test]
    fn event_kinds_typescript_contains_core_event_constants() {
        let output = render_generated_event_kinds();

        assert!(output.contains("export const TOKEN = kind(\"token\", \"stream\");"));
        assert!(
            output.contains("export const NODE_OUTPUT = kind(\"node_output\", \"observability\");")
        );
    }

    #[test]
    fn event_kinds_typescript_contains_core_event_kinds_array() {
        let output = render_generated_event_kinds();

        assert!(output.contains("export const CORE_EVENT_KINDS = ["));
        assert!(output.contains("  TOKEN,"));
        assert!(output.contains("export type CoreEventKindName ="));
    }

    #[test]
    fn event_kinds_typescript_preserves_terminal_flags() {
        let output = render_generated_event_kinds();

        assert!(
            output.contains("export const LLM_DONE = kind(\"llm_done\", \"lifecycle\", true);")
        );
        assert!(output.contains("export const ERROR = kind(\"error\", \"error\", true);"));
        assert!(output.contains("export const TOKEN = kind(\"token\", \"stream\");"));
    }

    #[test]
    fn event_kind_identifier_is_typescript_safe() {
        assert_eq!(ts_identifier("node_output"), "NODE_OUTPUT");
        assert_eq!(ts_identifier("vendor.event-start"), "VENDOR_EVENT_START");
        assert_eq!(ts_identifier("3p_event"), "_3P_EVENT");
    }

    #[test]
    fn core_event_kind_identifiers_are_unique() {
        let identifiers = event_kind_identifiers();
        assert_eq!(identifiers.len(), CORE_EVENT_KINDS.len());
    }
}
