//! Bound-tree contract record codegen: every `apxm.frontend-graph` `$defs`
//! object and discriminated union, projected into both authoring frontends
//! from the published schema itself.
//!
//! This is §4 item 1 of `docs/ideas/frontend-vocabulary-generation.md`: for
//! each `$defs` entry with `type: object`, `required`, `properties`, and
//! `additionalProperties: false`, emit one record type named for its `$defs`
//! key. A `$defs` entry that is instead a `oneOf` discriminated by a `const`
//! property (`ValueExpression`, `ControlPredicate`, `PredicateLiteral`) emits
//! a union of one record per branch. Enum- and const-typed fields resolve
//! through the same `FAMILIES` table `codegen_frontend_vocabulary` projects,
//! via `family_for_def_enum` / `family_for_discriminated_const`, so a set the
//! schema widens or narrows moves here without a second schema-path resolver.
//!
//! `PredicateLiteral`'s three-branch `oneOf` is the one place the schema does
//! not name its branches: unlike `ValueExpression` and `ControlPredicate`,
//! whose branches are all `$ref`s into named `$defs` entries, `PredicateLiteral`
//! states its branches as anonymous inline objects discriminated by
//! `scalar_type`. `BRANCH_NAMES` assigns `BooleanLiteral` / `StringLiteral` /
//! `IntegerLiteral` / `NullLiteral` — a naming convention this generator
//! invents, not one the contract states, because nothing else names them.
//!
//! `PermissionDecision` is a `$ref` target here (`CapabilityRequirement.requested_permission`)
//! but is not re-emitted: `codegen_permissions` already owns it as `Permission`,
//! and that generated type is imported rather than duplicated.
//!
//! This module implements §4 item 1 only. §4 item 2 (composing `BoundCall` /
//! `BoundControl` from these records) is hand-written in `_bound_tree.py` and
//! `bound-tree.ts`; §4 item 3 (`bound-tree.ts` itself) is hand-written; §6
//! (diagnostic-code wiring) is not implemented here. §5's serializers are
//! generated beside these types by `codegen_frontend_serializers`, which reads
//! `RECORDS`, `UNIONS`, and `fields_for` from here so one field list serves the
//! record type and its serializer.

use serde_json::Value;

