//! FrontendGraph vocabulary codegen: every closed string set the
//! `apxm.frontend-graph` contract states, projected into both authoring
//! frontends from the published schema itself.
//!
//! The source of truth is the contract file, not either frontend and not the
//! Rust consumer enums in `apxm_program::frontend_graph`. Both frontends emit
//! FrontendGraph documents that Rust decodes with `deny_unknown_fields`, so a
//! member typed by hand in Python or TypeScript that the schema does not state
//! is a document Rust rejects — which is exactly the drift this projection
//! removes. `semantic_conformance` already pins the Rust enums against the same
//! schema paths, so schema, Rust, Python, and TypeScript resolve one set.
//!
//! Two closed sets the schema states are deliberately **not** emitted here:
//! `PermissionDecision`, which `codegen_permissions` already owns and which
//! would otherwise gain a second spelling, and anything naming an AIS
//! operation — the schema states none, and a test holds the emitted text
//! against the frontend-surface manifest's own `non_public` list.

