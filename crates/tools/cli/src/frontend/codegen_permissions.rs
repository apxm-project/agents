//! Permission decision codegen: the author-facing `Allow` / `Ask` / `Deny`
//! vocabulary, projected into both authoring frontends from the one Rust
//! definition in `apxm_ais::permissions`.
//!
//! The projection is by **enumeration of the closed decision set**, so a
//! fourth decision cannot appear in an authoring package without appearing in
//! the machine first. Each decision is emitted twice: as the wire string an
//! author never has to type, and as the marker they import — a marker that is
//! usable bare (`permission=Allow`) and callable to attach the reason the
//! request gives (`permission=Ask("Writes files on the host.")`).

use apxm_ais::permissions::{DECISION_KEY, PermissionDecision, REASON_KEY};

pub const PYTHON_PERMISSIONS_FILE: &str = "permissions.py";
pub const TYPESCRIPT_PERMISSIONS_FILE: &str = "permissions.ts";

const PYTHON_HEADER: &str = "# AUTO-GENERATED by apxm codegen permissions; DO NOT EDIT.";
const TYPESCRIPT_HEADER: &str = "// AUTO-GENERATED by apxm codegen permissions; DO NOT EDIT.";

/// A generated decision: the marker authors import, the constant naming its
/// wire value, and the wire value itself.
struct Decision {
    marker: String,
    constant: String,
    value: &'static str,
}

fn decisions() -> Vec<Decision> {
    PermissionDecision::DECISIONS
        .into_iter()
        .map(|value| {
            let mut marker = String::with_capacity(value.len());
            let mut characters = value.chars();
            if let Some(first) = characters.next() {
                marker.extend(first.to_uppercase());
            }
            marker.push_str(characters.as_str());
            Decision {
                marker,
                constant: value.to_ascii_uppercase(),
                value,
            }
        })
        .collect()
}

fn quote(value: &str) -> String {
    serde_json::to_string(value).expect("decision string literal")
}

/// Concatenate one rendered member per line. `collect::<String>()` over a
/// `map(format!)` is the same string but trips `clippy::format_collect`; this
/// is the shape `codegen_capabilities` already uses.
fn members(rendered: impl Iterator<Item = String>) -> String {
    let mut buf = String::new();
    for member in rendered {
        buf.push_str(&member);
    }
    buf
}

pub fn render_permissions_python() -> String {
    let decisions = decisions();
    let mut buf = String::new();
    buf.push_str(PYTHON_HEADER);
    buf.push_str(
        "\n\"\"\"The permission decisions an Agent Program may request for a capability.\n\n\
         ``Tool(\"cap.write\", permission=Ask(\"Writes files on the host.\"))`` records what\n\
         the program asks the machine to do with a capability. A request is not a grant:\n\
         the resolution layer stack may narrow what a program asked for and may never\n\
         widen it, so importing a decision here confers no authority at all.\n\n\
         Import the marker instead of retyping the string: a misspelled marker is an\n\
         ImportError, a misspelled string is a decision nothing recognizes.\n\"\"\"\n\n\
         from __future__ import annotations\n\n\
         from dataclasses import dataclass\n\
         from typing import Final, Literal, Optional, TypeAlias\n\n",
    );

    buf.push_str(&format!(
        "PermissionDecision: TypeAlias = Literal[{}\n]\n\n\n",
        members(
            decisions
                .iter()
                .map(|decision| format!("\n    {},", quote(decision.value)))
        )
    ));

    buf.push_str(&format!(
        "@dataclass(frozen=True, slots=True)\n\
         class Permission:\n    \
         \"\"\"One requested decision and, when it says, why it was requested.\"\"\"\n\n    \
         {DECISION_KEY}: PermissionDecision\n    \
         {REASON_KEY}: Optional[str] = None\n\n    \
         def __call__(self, {REASON_KEY}: str) -> \"Permission\":\n        \
         \"\"\"The same decision, carrying the reason the program gives for it.\"\"\"\n        \
         return Permission(self.{DECISION_KEY}, {REASON_KEY})\n\n\n"
    ));

    for decision in &decisions {
        buf.push_str(&format!(
            "{}: Final[PermissionDecision] = {}\n",
            decision.constant,
            quote(decision.value)
        ));
    }
    buf.push('\n');
    for decision in &decisions {
        buf.push_str(&format!(
            "{}: Final[Permission] = Permission({})\n",
            decision.marker, decision.constant
        ));
    }

    buf.push_str(&format!(
        "\nPERMISSION_DECISIONS: Final[tuple[PermissionDecision, ...]] = ({}\n)\n",
        members(
            decisions
                .iter()
                .map(|decision| format!("\n    {},", decision.constant))
        )
    ));

    buf.push_str("\n__all__ = [");
    for name in exported_names(&decisions) {
        buf.push_str(&format!("\n    {},", quote(&name)));
    }
    buf.push_str("\n]\n");
    buf
}

pub fn render_permissions_typescript() -> String {
    let decisions = decisions();
    let mut buf = String::new();
    buf.push_str(TYPESCRIPT_HEADER);
    buf.push_str(
        "\n// The permission decisions an Agent Program may request for a capability.\n\
         //\n\
         // `Tool(\"cap.write\", { permission: Ask(\"Writes files on the host.\") })` records\n\
         // what the program asks the machine to do with a capability. A request is not a\n\
         // grant: the resolution layer stack may narrow what a program asked for and may\n\
         // never widen it, so importing a decision here confers no authority at all.\n\n",
    );

    buf.push_str(&format!(
        "export type PermissionDecision ={};\n",
        members(
            decisions
                .iter()
                .map(|decision| format!("\n  | {}", quote(decision.value)))
        )
    ));
    buf.push_str(&format!(
        "export type Permission = {{\n  readonly {DECISION_KEY}: PermissionDecision;\n  readonly {REASON_KEY}?: string;\n}};\n\
         /** A decision usable bare or called with the reason the program gives for it. */\n\
         export type PermissionMarker = Permission & ((reason: string) => Permission);\n\n\
         function marker(decision: PermissionDecision): PermissionMarker {{\n  \
         const attach = (reason: string): Permission => ({{ decision, reason }});\n  \
         return Object.assign(attach, {{ decision }}) as PermissionMarker;\n}}\n\n"
    ));

    for decision in &decisions {
        buf.push_str(&format!(
            "export const {} = {} satisfies PermissionDecision;\n",
            decision.constant,
            quote(decision.value)
        ));
    }
    buf.push('\n');
    for decision in &decisions {
        buf.push_str(&format!(
            "export const {}: PermissionMarker = marker({});\n",
            decision.marker, decision.constant
        ));
    }

    buf.push_str(&format!(
        "\nexport const PERMISSION_DECISIONS = [{}\n] as const satisfies readonly PermissionDecision[];\n",
        members(
            decisions
                .iter()
                .map(|decision| format!("\n  {},", decision.constant))
        )
    ));
    buf
}

fn exported_names(decisions: &[Decision]) -> Vec<String> {
    let mut names = vec!["Permission".to_string(), "PermissionDecision".to_string()];
    names.extend(decisions.iter().map(|decision| decision.marker.clone()));
    names.extend(decisions.iter().map(|decision| decision.constant.clone()));
    names.push("PERMISSION_DECISIONS".to_string());
    names
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The authoring vocabulary is the machine's, enumerated — not a
    /// hand-kept list that could gain a decision the machine cannot resolve
    /// or keep one the machine dropped.
    #[test]
    fn generated_vocabulary_is_exactly_the_closed_decision_set() {
        for generated in [render_permissions_python(), render_permissions_typescript()] {
            for decision in PermissionDecision::DECISIONS {
                assert!(generated.contains(&quote(decision)), "{decision}");
            }
            for absent in ["require_approval", "edit_args", "escalate", "elevate"] {
                assert!(!generated.contains(absent), "{absent}: {generated}");
            }
        }
    }

    /// Every decision is importable bare and callable with a reason, so an
    /// author never writes the wire shape by hand.
    #[test]
    fn generated_markers_are_both_values_and_reason_constructors() {
        let python = render_permissions_python();
        assert!(python.contains("Allow: Final[Permission] = Permission(ALLOW)"));
        assert!(python.contains("Ask: Final[Permission] = Permission(ASK)"));
        assert!(python.contains("def __call__(self, reason: str) -> \"Permission\":"));

        let typescript = render_permissions_typescript();
        assert!(typescript.contains("export const Allow: PermissionMarker = marker(ALLOW);"));
        assert!(typescript.contains("export const Deny: PermissionMarker = marker(DENY);"));
        assert!(typescript.contains("export type PermissionMarker"));
    }

    /// This catalogue lands in the same packages the authoring surface ships,
    /// so it must not smuggle in the operation vocabulary the frontend-surface
    /// manifest keeps off it.
    #[test]
    fn generated_vocabulary_publishes_no_operation_names() {
        for generated in [render_permissions_python(), render_permissions_typescript()] {
            for marker in [
                "model.call",
                "capability.invoke",
                "program.new",
                "program.invoke",
                "await.event",
                "ais.",
                "OP_",
                "FIVE_OPS",
            ] {
                assert!(!generated.contains(marker), "{marker}: {generated}");
            }
        }
    }
}
