fn typescript_scalar_type(scalar: &str) -> &'static str {
    match scalar {
        "list" => "unknown[]",
        "boolean" => "boolean",
        "integer" => "number",
        "string" => "string",
        other => panic!("unhandled corpus scalar {other}"),
    }
}

fn typescript_expression(node: &Value) -> String {
    let kind = string(node, "expr");
    let arguments = || {
        array(node, "arguments")
            .iter()
            .map(typescript_expression)
            .collect::<Vec<_>>()
            .join(", ")
    };
    match kind.as_str() {
        "name" => string(node, "name"),
        "integer" => node["value"].to_string(),
        "field" => format!("{}.{}", string(node, "name"), string(node, "field")),
        "context" => "agent.context".to_string(),
        "effect" => format!("await {}({})", string(node, "binding"), arguments()),
        "unawaited_effect" => format!("{}({})", string(node, "binding"), arguments()),
        "plain_call" => format!("{}({})", string(node, "callee"), arguments()),
        "invoke" => format!("await {}.invoke({})", string(node, "instance"), arguments()),
        "await_event" => format!("await {}.wait()", string(node, "event")),
        other => panic!("unhandled corpus expression {other}"),
    }
}

/// The object literal one Context's declared defaults, overridden by `values`,
/// state. TypeScript states every field where Python names only the overrides.
fn typescript_context_literal(corpus: &Value, name: &str, values: &Map<String, Value>) -> String {
    let context = context_named(corpus, name);
    let fields: Vec<String> = array(context, "fields")
        .iter()
        .map(|field| {
            let field_name = string(field, "name");
            let value = values.get(&field_name).unwrap_or(&field["default"]);
            format!("{field_name}: {}", typescript_literal(value))
        })
        .collect();
    format!("{{ {} }}", fields.join(", "))
}

fn typescript_body(
    corpus: &Value,
    body: &[Value],
    indent: usize,
    declared: &mut BTreeSet<String>,
) -> Vec<String> {
    let pad = " ".repeat(indent);
    let mut lines = Vec::new();
    for statement in body {
        let kind = string(statement, "stmt");
        match kind.as_str() {
            "let_null" => {
                let name = string(statement, "name");
                declared.insert(name.clone());
                lines.push(format!("{pad}let {name}: any = null;"));
            }
            "bind" => {
                let name = string(statement, "name");
                let keyword = if declared.contains(&name) {
                    ""
                } else {
                    "const "
                };
                declared.insert(name.clone());
                lines.push(format!(
                    "{pad}{keyword}{name} = {};",
                    typescript_expression(&statement["value"])
                ));
            }
            "return" => lines.push(format!(
                "{pad}return {};",
                typescript_expression(&statement["value"])
            )),
            "expr" => lines.push(format!(
                "{pad}{};",
                typescript_expression(&statement["value"])
            )),
            "loop_forever" => {
                lines.push(format!("{pad}while (true) {{"));
                lines.extend(typescript_body(
                    corpus,
                    array(statement, "body"),
                    indent + 2,
                    declared,
                ));
                lines.push(format!("{pad}}}"));
            }
            "if_not_null" => {
                lines.push(format!(
                    "{pad}if ({} !== null) {{",
                    typescript_expression(&statement["value"])
                ));
                lines.extend(typescript_body(
                    corpus,
                    array(statement, "body"),
                    indent + 2,
                    declared,
                ));
                lines.push(format!("{pad}}}"));
            }
            "if_equals" => {
                lines.push(format!(
                    "{pad}if ({} === {}) {{",
                    typescript_expression(&statement["left"]),
                    typescript_expression(&statement["right"])
                ));
                lines.extend(typescript_body(
                    corpus,
                    array(statement, "body"),
                    indent + 2,
                    declared,
                ));
                lines.push(format!("{pad}}}"));
            }
            "set_context" => {
                let values = statement["values"]
                    .as_object()
                    .cloned()
                    .unwrap_or_else(Map::new);
                lines.push(format!(
                    "{pad}agent.context = {};",
                    typescript_context_literal(corpus, &string(statement, "context"), &values)
                ));
            }
            "yield" => lines.push(format!(
                "{pad}{} = await agent.yield_({});",
                string(statement, "name"),
                typescript_expression(&statement["value"])
            )),
            "new_program" => {
                let name = string(statement, "name");
                declared.insert(name.clone());
                lines.push(format!(
                    "{pad}const {name} = {}.new({{ context: {} }});",
                    string(statement, "program"),
                    typescript_context_literal(corpus, &string(statement, "context"), &Map::new())
                ));
            }
            "task_group" => {
                lines.push(format!("{pad}await TaskGroup.run(async () => {{"));
                lines.extend(typescript_body(
                    corpus,
                    array(statement, "body"),
                    indent + 2,
                    declared,
                ));
                lines.push(format!("{pad}}});"));
            }
            "shadow_binding" => {
                let name = string(statement, "name");
                declared.insert(name.clone());
                lines.push(format!("{pad}const {name} = async (value: any) => value;"));
            }
            other => panic!("unhandled corpus statement {other}"),
        }
    }
    lines
}

fn typescript_declaration(declaration: &Value) -> String {
    let marker = string(declaration, "marker");
    let typed = if marker == "Event" {
        "<Input>"
    } else {
        "<Input, Output>"
    };
    let options = match declaration.get("permission") {
        None => String::new(),
        Some(permission) if permission["decision"] == "allow" => {
            ", { permission: Allow }".to_string()
        }
        Some(permission) => format!(
            ", {{ permission: Ask({}) }}",
            typescript_string(&string(permission, "reason"))
        ),
    };
    format!(
        "const {} = {marker}{typed}({}{options});",
        string(declaration, "name"),
        typescript_string(&string(declaration, "target_ref"))
    )
}

/// The authored TypeScript module one vector's programs are captured from.
fn typescript_source_text(corpus: &Value, vector: &Value) -> String {
    let mut lines = vec![
        "import { Agent, Capability, Context, Event, Hook, Model, TaskGroup, Tool } from \"@apxm/frontend\";"
            .to_string(),
        String::new(),
    ];
    for type_ref in array(corpus, "type_refs") {
        lines.push(format!(
            "type {} = any;",
            type_ref.as_str().expect("a type ref is a string")
        ));
    }
    let contexts = vector_contexts(corpus, vector);
    for name in &contexts {
        let context = context_named(corpus, name);
        let fields: Vec<String> = array(context, "fields")
            .iter()
            .map(|field| {
                format!(
                    "{}: {}",
                    string(field, "name"),
                    typescript_scalar_type(&string(field, "scalar"))
                )
            })
            .collect();
        lines.push(format!("type {name} = {{ {} }};", fields.join(", ")));
    }
    lines.push(String::new());
    for name in &contexts {
        lines.push(format!(
            "const {name} = Context<{name}>({});",
            typescript_context_literal(corpus, name, &Map::new())
        ));
    }
    for declaration in array(vector, "declarations") {
        lines.push(typescript_declaration(declaration));
    }
    for program in array(vector, "programs") {
        lines.push(String::new());
        lines.extend(typescript_program_text(corpus, program));
        for hook in array(program, "hooks") {
            lines.push(String::new());
            lines.extend(typescript_hook_text(corpus, program, hook));
        }
    }
    let mut text = lines.join("\n");
    text.push('\n');
    text
}

fn typescript_program_text(corpus: &Value, program: &Value) -> Vec<String> {
    let context = program.get("context").and_then(Value::as_str);
    let generics = match context {
        Some(context) => format!(
            "<{}, {}, {context}>",
            string(program, "input"),
            string(program, "output")
        ),
        None => format!(
            "<{}, {}>",
            string(program, "input"),
            string(program, "output")
        ),
    };
    let mut lines = vec![
        format!(
            "const {} = Agent{generics}({{",
            string(program, "program_id")
        ),
        format!(
            "  name: {},",
            typescript_string(&string(program, "program_id"))
        ),
    ];
    if let Some(context) = context {
        lines.push(format!("  context: {context},"));
    }
    lines.push("  async run(agent, input) {".to_string());
    lines.extend(typescript_body(
        corpus,
        array(program, "body"),
        4,
        &mut BTreeSet::new(),
    ));
    lines.push("  },".to_string());
    lines.push("});".to_string());
    lines
}

fn typescript_hook_text(corpus: &Value, program: &Value, hook: &Value) -> Vec<String> {
    let context = program
        .get("context")
        .and_then(Value::as_str)
        .unwrap_or("unknown");
    let mut lines = vec![
        format!(
            "const {} = Hook.{}<{context}>({{",
            string(hook, "name"),
            string(hook, "phase")
        ),
        format!("  agent: {},", string(program, "program_id")),
        format!("  target: {},", string(hook, "target")),
        format!("  scope: {},", typescript_string(&string(hook, "scope"))),
        "  async run(agent) {".to_string(),
    ];
    lines.extend(typescript_body(
        corpus,
        array(hook, "body"),
        4,
        &mut BTreeSet::new(),
    ));
    lines.push("  },".to_string());
    lines.push("});".to_string());
    lines
}

fn typescript_agent_call(program: &Value) -> String {
    let context = match program.get("context").and_then(Value::as_str) {
        Some(context) => format!(" context: {context},"),
        None => String::new(),
    };
    format!(
        "  const {id} = Agent<Input, Output>({{ name: {name},{context} async run() {{ return null; }} }});",
        id = string(program, "program_id"),
        name = typescript_string(&string(program, "program_id"))
    )
}

