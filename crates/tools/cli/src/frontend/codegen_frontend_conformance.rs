//! Frontend-conformance codegen: one shared corpus of authored-source fixtures
//! and expected FrontendGraph facts, projected into a runnable harness for
//! every registered authoring language.
//!
//! `contracts/vectors/apxm.frontend-conformance.json` states each vector once —
//! its declarations, its programs' bodies in a language-neutral statement
//! vocabulary, and what the resulting FrontendGraph, canonical AIR, and compiled
//! artifact must say. This generator projects that one statement into Python and
//! TypeScript. Neither language restates a fixture, so a vector cannot pass in
//! one language because its hand-written mirror in the other drifted: adding a
//! vector adds a case to both harnesses at once, and a language that does not
//! implement it fails.
//!
//! **The corpus is inlined here, at generation time, rather than read at test
//! time.** Neither authoring package ships `contracts/`: the Python wheel
//! packages `apxm_program*` only, and `@apxm/frontend` publishes `dist` only. A
//! harness that opened `contracts/vectors/...` would therefore work from a repo
//! checkout and fail from an installed package — the two configurations
//! `tests_program/test_packed_package.py` and `test/packed-package.test.ts`
//! exercise. TypeScript adds a second reason: `tsc` erases the typed interface
//! an Agent capture reads back, and the published package carries no
//! `inlineSources` map, so a TypeScript fixture cannot be recovered from the
//! running module and has to be carried as authored text either way. Inlining is
//! also what every other generator here does with the schemas it projects.
//!
//! Four files come out of one arm, because a harness is only a gate if both
//! halves are generated:
//!
//! * `apxm_program/_generated/conformance.py` and `src/generated/conformance.ts`
//!   carry the corpus, the fixtures, and the query evaluator. They live inside
//!   the packages so an installed package carries its own conformance harness.
//! * `tests_program/test_frontend_conformance.py` and
//!   `test/frontend-conformance.test.ts` are the test-runner invokers. They are
//!   generated too: a hand-written invoker could be deleted and that language
//!   would silently stop being checked.
//!
//! Python and TypeScript reach their capture entry differently, and the
//! difference is forced by the languages rather than chosen. Python's capture
//! reads an `async def` back through `inspect.getsource`, so the Python harness
//! carries its fixtures as real generated module code. TypeScript's capture
//! reads authored text, which the harness supplies through the package's own
//! `submitAuthoredSource` before calling the public `Agent(...)`. Both paths run
//! entirely through the surface an installed package publishes.

use std::collections::BTreeSet;

use serde_json::{Map, Value};

pub const PYTHON_CONFORMANCE_FILE: &str = "conformance.py";
pub const TYPESCRIPT_CONFORMANCE_FILE: &str = "conformance.ts";
pub const PYTHON_CONFORMANCE_TEST_FILE: &str = "test_frontend_conformance.py";
pub const TYPESCRIPT_CONFORMANCE_TEST_FILE: &str = "frontend-conformance.test.ts";

const CORPUS_JSON: &str = include_str!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../../contracts/vectors/apxm.frontend-conformance.json"
));

const PYTHON_HEADER: &str = "# AUTO-GENERATED by apxm codegen frontend-conformance; DO NOT EDIT.";
const TYPESCRIPT_HEADER: &str =
    "// AUTO-GENERATED by apxm codegen frontend-conformance; DO NOT EDIT.";

/// The one reference a corpus declaration uses to mean "a package-local handler
/// object rather than an exact typed reference". Each language projects it into
/// whatever its own frontend would reject.
const HANDLER_OBJECT_REFERENCE: &str = "@handler_object";

pub fn corpus() -> Value {
    serde_json::from_str(CORPUS_JSON).expect("apxm.frontend-conformance corpus parses")
}

fn vectors(corpus: &Value) -> &Vec<Value> {
    corpus["vectors"]
        .as_array()
        .expect("the corpus states a vectors array")
}

fn string(value: &Value, key: &str) -> String {
    value[key]
        .as_str()
        .unwrap_or_else(|| panic!("the corpus states a string {key}"))
        .to_string()
}

fn array<'a>(value: &'a Value, key: &str) -> &'a [Value] {
    value
        .get(key)
        .and_then(Value::as_array)
        .map(Vec::as_slice)
        .unwrap_or(&[])
}

/// The Context declaration one name refers to, out of the corpus's shared set.
fn context_named<'a>(corpus: &'a Value, name: &str) -> &'a Value {
    array(corpus, "contexts")
        .iter()
        .find(|context| context["name"] == *name)
        .unwrap_or_else(|| panic!("the corpus declares a Context named {name}"))
}

/// The Contexts one vector uses, in the order both languages declare them.
fn vector_contexts(corpus: &Value, vector: &Value) -> Vec<String> {
    let mut names: Vec<String> = Vec::new();
    for program in array(vector, "programs") {
        if let Some(name) = program.get("context").and_then(Value::as_str) {
            if !names.iter().any(|found| found == name) {
                names.push(name.to_string());
            }
        }
        walk(array(program, "body"), &mut |statement| {
            if let Some(name) = statement.get("context").and_then(Value::as_str) {
                if array(corpus, "contexts")
                    .iter()
                    .any(|context| context["name"] == *name)
                    && !names.iter().any(|found| found == name)
                {
                    names.push(name.to_string());
                }
            }
        });
    }
    names
}

fn walk(body: &[Value], visit: &mut impl FnMut(&Value)) {
    for statement in body {
        visit(statement);
        walk(array(statement, "body"), visit);
    }
}

