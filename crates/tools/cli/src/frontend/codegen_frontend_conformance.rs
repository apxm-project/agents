/// Render one JSON value as the Python literal that reconstructs it.
fn python_literal(value: &Value) -> String {
    match value {
        Value::Null => "None".to_string(),
        Value::Bool(true) => "True".to_string(),
        Value::Bool(false) => "False".to_string(),
        Value::Number(number) => number.to_string(),
        Value::String(text) => python_string(text),
        Value::Array(items) => format!(
            "[{}]",
            items
                .iter()
                .map(python_literal)
                .collect::<Vec<_>>()
                .join(", ")
        ),
        Value::Object(fields) => format!(
            "{{{}}}",
            fields
                .iter()
                .map(|(key, entry)| format!("{}: {}", python_string(key), python_literal(entry)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

/// A double-quoted Python string literal, which JSON string escaping produces.
fn python_string(text: &str) -> String {
    Value::String(text.to_string()).to_string()
}

/// Render one JSON value as the TypeScript literal that reconstructs it, which
/// for every shape the corpus uses is the JSON text itself.
fn typescript_literal(value: &Value) -> String {
    value.to_string()
}

fn typescript_string(text: &str) -> String {
    Value::String(text.to_string()).to_string()
}

