fn python_scalar_type(scalar: &str) -> &'static str {
    match scalar {
        "list" => "tuple",
        "boolean" => "bool",
        "integer" => "int",
        "string" => "str",
        other => panic!("unhandled corpus scalar {other}"),
    }
}

fn python_default(scalar: &str, default: &Value) -> String {
    if scalar == "list" {
        return "()".to_string();
    }
    python_literal(default)
}

fn python_expression(node: &Value) -> String {
    let kind = string(node, "expr");
    let arguments = || {
        array(node, "arguments")
            .iter()
            .map(python_expression)
            .collect::<Vec<_>>()
            .join(", ")
    };
    match kind.as_str() {
        "name" => string(node, "name"),
        "integer" => node["value"].to_string(),
        "field" => format!(
            "{}[{}]",
            string(node, "name"),
            python_string(&string(node, "field"))
        ),
        "context" => "agent.context".to_string(),
        "effect" => format!("await {}({})", string(node, "binding"), arguments()),
        "unawaited_effect" => format!("{}({})", string(node, "binding"), arguments()),
        "plain_call" => format!("{}({})", string(node, "callee"), arguments()),
        "invoke" => format!("await {}.invoke({})", string(node, "instance"), arguments()),
        "await_event" => format!("await {}.wait()", string(node, "event")),
        other => panic!("unhandled corpus expression {other}"),
    }
}

fn python_body(corpus: &Value, body: &[Value], indent: usize) -> Vec<String> {
    let pad = " ".repeat(indent);
    let mut lines = Vec::new();
    for statement in body {
        let kind = string(statement, "stmt");
        let nested = || python_body(corpus, array(statement, "body"), indent + 4);
        match kind.as_str() {
            "let_null" => lines.push(format!("{pad}{} = None", string(statement, "name"))),
            "bind" => lines.push(format!(
                "{pad}{} = {}",
                string(statement, "name"),
                python_expression(&statement["value"])
            )),
            "return" => lines.push(format!(
                "{pad}return {}",
                python_expression(&statement["value"])
            )),
            "expr" => lines.push(format!("{pad}{}", python_expression(&statement["value"]))),
            "loop_forever" => {
                lines.push(format!("{pad}while True:"));
                lines.extend(nested());
            }
            "if_not_null" => {
                lines.push(format!(
                    "{pad}if {} is not None:",
                    python_expression(&statement["value"])
                ));
                lines.extend(nested());
            }
            "if_equals" => {
                lines.push(format!(
                    "{pad}if {} == {}:",
                    python_expression(&statement["left"]),
                    python_expression(&statement["right"])
                ));
                lines.extend(nested());
            }
            "set_context" => {
                let values = statement["values"]
                    .as_object()
                    .cloned()
                    .unwrap_or_else(Map::new);
                let arguments = values
                    .iter()
                    .map(|(key, value)| format!("{key}={}", python_literal(value)))
                    .collect::<Vec<_>>()
                    .join(", ");
                lines.push(format!(
                    "{pad}agent.context = {}({arguments})",
                    string(statement, "context")
                ));
            }
            "yield" => lines.push(format!(
                "{pad}{} = await agent.yield_({})",
                string(statement, "name"),
                python_expression(&statement["value"])
            )),
            "new_program" => lines.push(format!(
                "{pad}{} = {}.new(context={}())",
                string(statement, "name"),
                string(statement, "program"),
                string(statement, "context")
            )),
            "task_group" => {
                lines.push(format!("{pad}async with TaskGroup():"));
                lines.extend(nested());
            }
            "shadow_binding" => lines.push(format!(
                "{pad}{} = lambda value: value",
                string(statement, "name")
            )),
            other => panic!("unhandled corpus statement {other}"),
        }
    }
    lines
}

fn python_declaration(declaration: &Value) -> String {
    let marker = string(declaration, "marker");
    let typed = if marker == "Event" {
        "[object]"
    } else {
        "[object, object]"
    };
    let permission = match declaration.get("permission") {
        None => String::new(),
        Some(permission) if permission["decision"] == "allow" => ", permission=Allow".to_string(),
        Some(permission) => format!(
            ", permission=Ask({})",
            python_string(&string(permission, "reason"))
        ),
    };
    format!(
        "{} = {marker}{typed}({}{permission})",
        string(declaration, "name"),
        python_string(&string(declaration, "target_ref"))
    )
}

fn python_context(context: &Value) -> Vec<String> {
    let mut lines = vec![
        "@Context".to_string(),
        format!("class {}:", string(context, "name")),
    ];
    for field in array(context, "fields") {
        let scalar = string(field, "scalar");
        lines.push(format!(
            "    {}: {} = {}",
            string(field, "name"),
            python_scalar_type(&scalar),
            python_default(&scalar, &field["default"])
        ));
    }
    lines
}

fn python_hook(corpus: &Value, hook: &Value) -> Vec<String> {
    let mut lines = vec![
        format!(
            "@Hook.{}(target={}, scope={})",
            string(hook, "phase"),
            python_string(&string(hook, "target")),
            python_string(&string(hook, "scope"))
        ),
        format!("async def {}(agent) -> None:", string(hook, "name")),
    ];
    let body = python_body(corpus, array(hook, "body"), 4);
    if body.is_empty() {
        lines.push("    return None".to_string());
    } else {
        lines.extend(body);
    }
    lines
}

fn python_program(corpus: &Value, program: &Value, indent: usize) -> Vec<String> {
    let pad = " ".repeat(indent);
    let mut arguments = vec![
        format!("input={}", string(program, "input")),
        format!("output={}", string(program, "output")),
    ];
    if let Some(context) = program.get("context").and_then(Value::as_str) {
        arguments.push(format!("context={context}"));
    }
    let mut lines = vec![
        format!("{pad}@Agent({})", arguments.join(", ")),
        format!(
            "{pad}async def {}(agent, input):",
            string(program, "program_id")
        ),
    ];
    lines.extend(python_body(corpus, array(program, "body"), indent + 4));
    lines
}

pub fn render_conformance_python() -> String {
    let corpus = corpus();
    let mut out: Vec<String> = Vec::new();
    out.push(PYTHON_HEADER.to_string());
    out.push(PYTHON_MODULE_DOC.to_string());
    out.push(String::new());
    out.push("from __future__ import annotations".to_string());
    out.push(String::new());
    out.push("import json".to_string());
    out.push("import re".to_string());
    out.push("from typing import Any, Optional".to_string());
    out.push(String::new());
    out.push(
        "from .. import Agent, Capability, Context, Event, Hook, Model, TaskGroup, Tool"
            .to_string(),
    );
    out.push("from ..permissions import Allow, Ask".to_string());
    out.push(String::new());
    out.push(PYTHON_RUNTIME.to_string());
    out.push(String::new());

    out.push("_EXPECTATIONS: dict[str, list[dict[str, Any]]] = {".to_string());
    for vector in vectors(&corpus) {
        let Some(expectations) = vector.get("expect") else {
            continue;
        };
        out.push(format!("    {}: [", python_string(&string(vector, "id"))));
        for expectation in expectations.as_array().expect("expect states an array") {
            out.push(format!("        {},", python_literal(expectation)));
        }
        out.push("    ],".to_string());
    }
    out.push("}".to_string());
    out.push(String::new());

    for type_ref in array(&corpus, "type_refs") {
        let name = type_ref.as_str().expect("a type ref is a string");
        out.push(format!("class {name}:"));
        out.push(
            "    \"\"\"A typed declaration the conformance corpus states an interface with.\"\"\""
                .to_string(),
        );
        out.push(String::new());
    }
    for context in array(&corpus, "contexts") {
        out.push(String::new());
        out.extend(python_context(context));
        out.push(String::new());
    }

    let mut ids: Vec<String> = Vec::new();
    for vector in vectors(&corpus) {
        let id = string(vector, "id");
        out.push(String::new());
        out.push(format!("# vector: {id}"));
        if let Some(rejections) = vector.get("declaration_rejections") {
            out.extend(python_declaration_rejections(&id, rejections));
        } else if let Some(rejects) = vector.get("rejects") {
            out.extend(python_rejection_vector(&corpus, &id, vector, rejects));
        } else {
            out.extend(python_program_vector(&corpus, &id, vector));
        }
        ids.push(id);
    }

    out.push(String::new());
    out.push(String::new());
    out.push("VECTOR_IDS: tuple[str, ...] = (".to_string());
    for id in &ids {
        out.push(format!("    {},", python_string(id)));
    }
    out.push(")".to_string());
    out.push(String::new());
    out.push("_VECTORS = {".to_string());
    for id in &ids {
        out.push(format!("    {}: _vector_{id},", python_string(id)));
    }
    out.push("}".to_string());
    out.push(String::new());
    out.push(PYTHON_TAIL.to_string());

    let mut rendered = out.join("\n");
    rendered.push('\n');
    rendered
}

fn python_declaration_rejections(id: &str, rejections: &Value) -> Vec<String> {
    let markers: Vec<String> = array(rejections, "markers")
        .iter()
        .map(|marker| marker.as_str().expect("a marker is a string").to_string())
        .collect();
    let message = string(rejections, "message_contains");
    vec![
        format!("def _vector_{id}() -> list[str]:"),
        "    failures: list[str] = []".to_string(),
        format!("    for marker in ({},):", markers.join(", ")),
        format!(
            "        for reference in {}:",
            python_literal(&rejections["references"])
        ),
        format!(
            "            argument: Any = (lambda: None) if reference == {} else reference",
            python_string(HANDLER_OBJECT_REFERENCE)
        ),
        "            try:".to_string(),
        "                marker(argument)".to_string(),
        "            except (ValueError, TypeError) as error:".to_string(),
        format!(
            "                if {} not in str(error):",
            python_string(&message)
        ),
        format!(
            "                    failures.append(_failure({}, f\"declaring {{reference!r}} was rejected with {{error}}\"))",
            python_string(id)
        ),
        "            else:".to_string(),
        format!(
            "                failures.append(_failure({}, f\"declaring {{reference!r}} was accepted, and the corpus states it is rejected\"))",
            python_string(id)
        ),
        "    return failures".to_string(),
    ]
}

fn python_rejection_vector(
    corpus: &Value,
    id: &str,
    vector: &Value,
    rejects: &Value,
) -> Vec<String> {
    let mut lines = vec![format!("def _vector_{id}() -> list[str]:")];
    for declaration in array(vector, "declarations") {
        lines.push(format!("    {}", python_declaration(declaration)));
    }
    lines.push("    try:".to_string());
    for program in array(vector, "programs") {
        lines.extend(python_program(corpus, program, 8));
    }
    lines.push("    except Exception as error:".to_string());
    match rejects.get("message_contains").and_then(Value::as_str) {
        None => lines.push("        return []".to_string()),
        Some(message) => {
            lines.push(format!(
                "        if {} in str(error):",
                python_string(message)
            ));
            lines.push("            return []".to_string());
            lines.push(format!(
                "        return [_failure({}, f\"rejected with {{str(error)!r}}, which does not state {}\")]",
                python_string(id),
                message.replace('"', "'")
            ));
        }
    }
    lines.push(format!(
        "    return [_failure({}, \"authoring was accepted, and the corpus states it is rejected\")]",
        python_string(id)
    ));
    lines
}

fn python_program_vector(corpus: &Value, id: &str, vector: &Value) -> Vec<String> {
    let mut lines = Vec::new();
    for declaration in array(vector, "declarations") {
        lines.push(python_declaration(declaration));
    }
    let mut hooks: Vec<String> = Vec::new();
    for program in array(vector, "programs") {
        // A Python Hook binds through the module globals its Agent resolves, so
        // it is declared above that Agent and removed again below it: a Hook
        // left in scope would bind into every later vector's capture too.
        for hook in array(program, "hooks") {
            lines.push(String::new());
            lines.extend(python_hook(corpus, hook));
            hooks.push(string(hook, "name"));
        }
        lines.push(String::new());
        lines.extend(python_program(corpus, program, 0));
    }
    for hook in hooks {
        lines.push(String::new());
        lines.push(format!("del {hook}"));
    }
    let subject = string(
        array(vector, "programs")
            .last()
            .expect("a program vector states at least one program"),
        "program_id",
    );
    lines.push(String::new());
    lines.push(format!("def _vector_{id}() -> list[str]:"));
    lines.push(format!(
        "    return _check({}, {subject}, _EXPECTATIONS[{}])",
        python_string(id),
        python_string(id)
    ));
    lines
}

