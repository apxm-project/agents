//! Capability-effect vocabulary drift gate between the Rust receipt enums and
//! the checked-in generated public clients.
//!
//! `crates/tools/cli/generated/{typescript/event-v1.ts,python/event_v1.py}` are
//! rendered by the contracts repository's generator from `apxm.event.v1`. This
//! crate's [`CapabilityEffectDispatchPath`] and
//! [`CapabilityEffectImplementationKind`] decide what a receipt can actually
//! carry on the wire and in persisted evidence. When a variant is retired here
//! but the schema still lists it, the generated clients keep advertising a name
//! this runtime rejects, and a client author types against execution that
//! cannot happen.
//!
//! The expected vocabulary is not a literal maintained in this file: each name
//! is produced by serializing the real enum variant through the same `serde`
//! `rename_all` attribute the decoder uses, and the variant lists are pinned by
//! exhaustive `match`es that fail compilation when a variant is added. The
//! observed vocabulary is parsed out of the generated files on disk. Neither
//! side of the comparison is authored by this test.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use super::payload::{CapabilityEffectDispatchPath, CapabilityEffectImplementationKind};

/// Repo-relative paths of the generated clients, for failure messages that
/// point at the file an operator must look at rather than an absolute path
/// from the machine that happened to run the gate.
const TYPESCRIPT_CLIENT: &str = "crates/tools/cli/generated/typescript/event-v1.ts";
const PYTHON_CLIENT: &str = "crates/tools/cli/generated/python/event_v1.py";

/// The repository that owns `apxm.event.v1` and the generator that renders the
/// clients above. A drift this gate reports is discharged there, not here:
/// the generated bytes must never be hand-edited to make this test pass.
const SCHEMA_OWNER: &str = "contracts (frozen/event.v1.json, tools/codegen.py)";

fn repo_root() -> PathBuf {
    // CARGO_MANIFEST_DIR is crates/machine/contracts.
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../..")
        .canonicalize()
        .expect("resolve repository root from the crate manifest directory")
}

fn read_client(relative: &str) -> String {
    let path = repo_root().join(relative);
    std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("read generated client {}: {error}", path.display()))
}

/// The wire name `serde` gives a variant, taken from the value itself rather
/// than restated as a literal.
fn wire_name<T: serde::Serialize + std::fmt::Debug>(variant: &T) -> String {
    match serde_json::to_value(variant).expect("serialize capability effect variant") {
        serde_json::Value::String(name) => name,
        other => panic!("expected {variant:?} to serialize to a string, got {other}"),
    }
}

/// Every `dispatch_path` name this runtime admits.
///
/// The `match` is a completeness pin: adding a variant to
/// [`CapabilityEffectDispatchPath`] makes it non-exhaustive and fails the
/// build until the variant is listed in `ALL` too.
fn admitted_dispatch_paths() -> BTreeSet<String> {
    const ALL: &[CapabilityEffectDispatchPath] = &[CapabilityEffectDispatchPath::InvCap];
    for variant in ALL {
        match variant {
            CapabilityEffectDispatchPath::InvCap => {}
        }
    }
    ALL.iter().map(wire_name).collect()
}

/// Every `implementation_kind` name this runtime admits, pinned the same way.
fn admitted_implementation_kinds() -> BTreeSet<String> {
    const ALL: &[CapabilityEffectImplementationKind] = &[
        CapabilityEffectImplementationKind::Native,
        CapabilityEffectImplementationKind::Typescript,
        CapabilityEffectImplementationKind::Host,
    ];
    for variant in ALL {
        match variant {
            CapabilityEffectImplementationKind::Native
            | CapabilityEffectImplementationKind::Typescript
            | CapabilityEffectImplementationKind::Host => {}
        }
    }
    ALL.iter().map(wire_name).collect()
}

/// Pull the single line declaring `field` out of a generated client, so a
/// malformed or renamed declaration fails loudly instead of silently matching
/// an empty vocabulary.
fn declaration_line<'a>(source: &'a str, relative: &str, field: &str) -> &'a str {
    let matches: Vec<&str> = source
        .lines()
        .filter(|line| line.trim_start().starts_with(&format!("{field}:")))
        .collect();
    assert_eq!(
        matches.len(),
        1,
        "{relative} must declare {field} exactly once; found {} declarations",
        matches.len()
    );
    matches[0]
}

/// Every quoted string literal on a line, in declaration order. Both generated
/// dialects spell their closed vocabularies as quoted literals — TypeScript as
/// a `"a" | "b"` union and Python as a `Literal['a', 'b']` — so one extractor
/// serves both.
fn quoted_literals(line: &str) -> BTreeSet<String> {
    let mut found = BTreeSet::new();
    let mut rest = line;
    while let Some(open) = rest.find(['"', '\'']) {
        let quote = rest.as_bytes()[open] as char;
        let after = &rest[open + 1..];
        let Some(close) = after.find(quote) else {
            break;
        };
        found.insert(after[..close].to_string());
        rest = &after[close + 1..];
    }
    found
}

fn assert_vocabulary(relative: &str, field: &str, admitted: &BTreeSet<String>) {
    let source = read_client(relative);
    let line = declaration_line(&source, relative, field);
    let published = quoted_literals(line);
    assert!(
        !published.is_empty(),
        "{relative} declares {field} with no vocabulary: {}",
        line.trim()
    );

    let undispatchable: Vec<&String> = published.difference(admitted).collect();
    let missing: Vec<&String> = admitted.difference(&published).collect();
    assert!(
        undispatchable.is_empty() && missing.is_empty(),
        "{relative} publishes a {field} vocabulary this runtime does not admit.\n  \
         published: {published:?}\n  \
         admitted:  {admitted:?}\n  \
         names this runtime rejects but the client advertises: {undispatchable:?}\n  \
         names this runtime admits but the client omits: {missing:?}\n  \
         This file is generated; do not edit it. Discharge in {SCHEMA_OWNER} by \
         aligning the apxm.event.v1 enum, then regenerate this client."
    );
}

/// A retired `dispatch_path` name must not survive in either generated client.
#[test]
fn generated_clients_publish_only_admitted_dispatch_paths() {
    let admitted = admitted_dispatch_paths();
    assert_vocabulary(TYPESCRIPT_CLIENT, "dispatch_path", &admitted);
    assert_vocabulary(PYTHON_CLIENT, "dispatch_path", &admitted);
}

/// A retired `implementation_kind` name must not survive in either generated
/// client.
#[test]
fn generated_clients_publish_only_admitted_implementation_kinds() {
    let admitted = admitted_implementation_kinds();
    assert_vocabulary(TYPESCRIPT_CLIENT, "implementation_kind", &admitted);
    assert_vocabulary(PYTHON_CLIENT, "implementation_kind", &admitted);
}
