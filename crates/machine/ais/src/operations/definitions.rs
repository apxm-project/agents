/// Lookup one semantic operation specification.
#[must_use]
pub fn get_operation_spec(op: SemanticOpKind) -> Option<&'static OperationSpec> {
    AIS_OPERATIONS.iter().find(|spec| spec.op_type == op)
}

/// Iterate all semantic operation specifications.
pub fn get_all_operations() -> impl Iterator<Item = &'static OperationSpec> {
    AIS_OPERATIONS.iter()
}

#[cfg(test)]
mod absence_tests {
    use super::*;

    #[test]
    fn catalogue_reports_exactly_five_public_semantic_operations() {
        assert_eq!(AIS_OPERATIONS.len(), 5);
        assert_eq!(WIRE_INDEXED_OPERATIONS.len(), 5);
        assert_eq!(SemanticOpKind::all().len(), 5);
    }

    #[test]
    fn wire_indices_are_dense_zero_based() {
        let mut indices: Vec<u32> = WIRE_INDEXED_OPERATIONS
            .iter()
            .map(|(index, _)| *index)
            .collect();
        indices.sort_unstable();
        assert_eq!(indices, vec![0, 1, 2, 3, 4]);
    }

    #[test]
    fn no_retired_or_structural_escape_in_semantic_catalogue() {
        for spec in AIS_OPERATIONS {
            let wire = spec.op_type.wire();
            assert!(
                !wire.contains("nop")
                    && !wire.contains("branch")
                    && !wire.contains("loop")
                    && !wire.contains("yield")
                    && !wire.contains("return")
                    && !wire.contains("switch")
                    && !wire.contains("try")
                    && !wire.contains("checkpoint")
                    && wire != "agent",
                "semantic catalogue must not contain structural/retired escape: {wire}"
            );
        }
    }

    #[test]
    fn tablegen_attrs_are_canonical() {
        for spec in AIS_OPERATIONS {
            for field in spec.fields {
                if field.name.contains('.') {
                    panic!(
                        "semantic operand field names must be flat identifiers: {}",
                        field.name
                    );
                }
            }
        }
    }
}
