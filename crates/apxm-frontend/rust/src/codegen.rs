use std::fs;
use std::path::Path;

use anyhow::Result;

use crate::registry::{
    FrontendAgentTemplate, FrontendConstant, FrontendEmissionSpec, agent_templates,
    emission_specs, graph_attr_constants, graph_metadata_constants, operation_specs,
};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFrontendFiles {
    pub constants_py: String,
    pub operations_py: String,
    pub agents_py: String,
    pub emission_py: String,
}

pub fn render_generated_files() -> GeneratedFrontendFiles {
    GeneratedFrontendFiles {
        constants_py: render_constants_module(),
        operations_py: render_operations_module(),
        agents_py: render_agents_module(),
        emission_py: render_emission_module(),
    }
}

pub fn render_generated_init() -> String {
    let mut buf = String::new();
    buf.push_str("\"\"\"Auto-generated APXM frontend bindings.\"\"\"\n\n");
    buf.push_str("from .agents import *\n");
    buf.push_str("from .constants import *\n");
    buf.push_str("from .emission import *\n");
    buf.push_str("from .operations import *\n");
    buf
}

pub fn render_generated_python() -> Vec<(&'static str, String)> {
    let rendered = render_generated_files();
    vec![
        ("__init__.py", render_generated_init()),
        ("constants.py", rendered.constants_py),
        ("operations.py", rendered.operations_py),
        ("agents.py", rendered.agents_py),
        ("emission.py", rendered.emission_py),
    ]
}

pub fn write_generated_python(output_dir: impl AsRef<Path>) -> Result<()> {
    let output_dir = output_dir.as_ref();
    fs::create_dir_all(output_dir)?;

    for (filename, content) in render_generated_python() {
        fs::write(output_dir.join(filename), content)?;
    }

    Ok(())
}

fn render_constants_module() -> String {
    let mut buf = String::new();
    buf.push_str("# AUTO-GENERATED by apxm-frontend; DO NOT EDIT.\n");
    buf.push_str("from typing import Final\n\n");

    buf.push_str("# Graph metadata keys\n");
    for item in graph_metadata_constants() {
        render_constant(&mut buf, &item);
    }

    buf.push_str("\n# Graph attribute keys\n");
    for item in graph_attr_constants() {
        render_constant(&mut buf, &item);
    }

    buf
}

fn render_operations_module() -> String {
    let mut buf = String::new();
    buf.push_str("# AUTO-GENERATED by apxm-frontend; DO NOT EDIT.\n");
    buf.push_str("from dataclasses import dataclass\n");
    buf.push_str("from typing import Final\n\n");
    buf.push_str("@dataclass(frozen=True)\n");
    buf.push_str("class OpSpec:\n");
    buf.push_str("    op: str\n");
    buf.push_str("    name: str\n");
    buf.push_str("    category: str\n");
    buf.push_str("    description: str\n");
    buf.push_str("    required_fields: tuple[str, ...]\n");
    buf.push_str("    optional_fields: tuple[str, ...]\n");
    buf.push_str("    produces_output: bool\n\n");

    let ops = operation_specs();
    for spec in &ops {
        let ident = py_identifier(&spec.op).to_ascii_uppercase();
        buf.push_str(&format!("{ident}: Final = OpSpec(\n"));
        buf.push_str(&format!("    op={},\n", py_string(&spec.op)));
        buf.push_str(&format!("    name={},\n", py_string(spec.name)));
        buf.push_str(&format!("    category={},\n", py_string(spec.category)));
        buf.push_str(&format!(
            "    description={},\n",
            py_string(spec.description)
        ));
        buf.push_str(&format!(
            "    required_fields={},\n",
            py_tuple(&spec.required_fields)
        ));
        buf.push_str(&format!(
            "    optional_fields={},\n",
            py_tuple(&spec.optional_fields)
        ));
        buf.push_str(&format!(
            "    produces_output={},\n",
            py_bool(spec.produces_output)
        ));
        buf.push_str(")\n\n");
    }

    buf.push_str("ALL_OPERATIONS: Final[tuple[OpSpec, ...]] = (\n");
    for spec in &ops {
        let ident = py_identifier(&spec.op).to_ascii_uppercase();
        buf.push_str(&format!("    {ident},\n"));
    }
    buf.push_str(")\n");
    buf
}

fn render_agents_module() -> String {
    let mut buf = String::new();
    buf.push_str("# AUTO-GENERATED by apxm-frontend; DO NOT EDIT.\n");
    buf.push_str("from dataclasses import dataclass\n");
    buf.push_str("from typing import Final\n\n");
    buf.push_str("@dataclass(frozen=True)\n");
    buf.push_str("class AgentRef:\n");
    buf.push_str("    name: str\n");
    buf.push_str("    command: str\n");
    buf.push_str("    default_mode: str | None\n");
    buf.push_str("    default_model: str | None\n\n");

    let templates = agent_templates();
    for item in &templates {
        let ident = py_identifier(&item.name);
        render_agent_ref(&mut buf, &ident, item);
    }

    buf.push_str("ALL_AGENTS: Final[tuple[AgentRef, ...]] = (\n");
    for item in &templates {
        buf.push_str(&format!("    {},\n", py_identifier(&item.name)));
    }
    buf.push_str(")\n");
    buf
}

fn render_emission_module() -> String {
    let mut buf = String::new();
    buf.push_str("# AUTO-GENERATED by apxm-frontend; DO NOT EDIT.\n");
    buf.push_str("\"\"\"MLIR emission helpers for AIS operations.\"\"\"\n\n");

    let specs = emission_specs();
    for spec in &specs {
        render_emission_fn(&mut buf, spec);
    }

    buf
}

fn render_emission_fn(buf: &mut String, spec: &FrontendEmissionSpec) {
    let fn_name = format!("emit_{}", spec.op.to_lowercase());

    buf.push_str(&format!("def {}(", fn_name));

    // Add context parameter if needed
    if spec.context_style != "None" {
        buf.push_str("ctx=None, ");
    }

    // Add positional attribute parameters
    for attr in &spec.positional_attrs {
        buf.push_str(&format!("{}, ", attr));
    }

    // Add keyword parameters with defaults
    for kw in &spec.keywords {
        buf.push_str(&format!("{}=None, ", kw));
    }

    buf.push_str("**attrs):\n");

    // Generate function body
    buf.push_str(&format!("    \"\"\"Emit MLIR for {} operation.\"\"\"\n", spec.op));
    buf.push_str("    parts = []\n\n");

    // Add result type prefix
    if spec.result_type != "Void" {
        buf.push_str("    parts.append(\"%0 = \")\n");
    }

    // Add operation mnemonic
    buf.push_str(&format!("    parts.append(\"ais.{}\")\n", spec.mlir_mnemonic));

    // Add primary attribute if present
    if let Some(primary) = &spec.primary_attr {
        buf.push_str(&format!("    if '{}' in attrs:\n", primary));
        buf.push_str(&format!("        parts.append(f' {{attrs[\"{}\"]}}\"')\n", primary));
    }

    // Add context
    match spec.context_style.as_str() {
        "Bracketed" => {
            buf.push_str("    if ctx:\n");
            buf.push_str("        parts.append(\" [\")\n");
            buf.push_str("        parts.append(\", \".join(str(c) for c in ctx))\n");
            buf.push_str("        parts.append(\"]\")\n");
        }
        "Parenthesized" => {
            buf.push_str("    if ctx:\n");
            buf.push_str("        parts.append(\" (\")\n");
            buf.push_str("        parts.append(\", \".join(str(c) for c in ctx))\n");
            buf.push_str("        parts.append(\")\")\n");
        }
        _ => {}
    }

    // Add result type annotation
    if spec.result_type != "Void" {
        let type_str = match spec.result_type.as_str() {
            "Token" => "!ais.token",
            "Handle" => "!ais.handle",
            _ => "!ais.token",
        };
        buf.push_str(&format!("    parts.append(\" : {}\")\n", type_str));
    }

    buf.push_str("    return ''.join(parts)\n\n");
}

fn render_constant(buf: &mut String, item: &FrontendConstant) {
    buf.push_str(&format!(
        "{}: Final[str] = {}\n",
        item.name,
        py_string(item.value)
    ));
}

fn render_agent_ref(buf: &mut String, ident: &str, item: &FrontendAgentTemplate) {
    buf.push_str(&format!("{ident}: Final = AgentRef(\n"));
    buf.push_str(&format!("    name={},\n", py_string(&item.name)));
    buf.push_str(&format!("    command={},\n", py_string(&item.command)));
    buf.push_str(&format!(
        "    default_mode={},\n",
        py_optional_string(item.default_mode.as_deref())
    ));
    buf.push_str(&format!(
        "    default_model={},\n",
        py_optional_string(item.default_model.as_deref())
    ));
    buf.push_str(")\n\n");
}

fn py_identifier(value: &str) -> String {
    let mut result = String::new();

    for (idx, ch) in value.chars().enumerate() {
        let mapped = if ch.is_ascii_alphanumeric() || ch == '_' {
            ch
        } else {
            '_'
        };

        if idx == 0 && mapped.is_ascii_digit() {
            result.push('_');
        }

        result.push(mapped.to_ascii_lowercase());
    }

    if result.is_empty() {
        "_generated".to_string()
    } else {
        result
    }
}

fn py_optional_string(value: Option<&str>) -> String {
    match value {
        Some(value) => py_string(value),
        None => "None".to_string(),
    }
}

fn py_string(value: &str) -> String {
    serde_json::to_string(value).expect("python string literal")
}

fn py_tuple(values: &[&str]) -> String {
    match values.len() {
        0 => "()".to_string(),
        1 => format!("({},)", py_string(values[0])),
        _ => {
            let joined = values
                .iter()
                .map(|value| py_string(value))
                .collect::<Vec<_>>()
                .join(", ");
            format!("({joined})")
        }
    }
}

fn py_bool(value: bool) -> &'static str {
    if value { "True" } else { "False" }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn constants_module_renders_model_constant() {
        let rendered = render_generated_files();
        assert!(
            rendered
                .constants_py
                .contains("MODEL: Final[str] = \"model\"")
        );
    }

    #[test]
    fn operations_module_renders_spawn_agent() {
        let rendered = render_generated_files();
        assert!(
            rendered
                .operations_py
                .contains("SPAWN_AGENT: Final = OpSpec(")
        );
        assert!(!rendered.operations_py.contains("produces_output=false"));
        assert!(!rendered.operations_py.contains("produces_output=true"));
    }

    #[test]
    fn agents_module_renders_claude() {
        let rendered = render_generated_files();
        assert!(rendered.agents_py.contains("claude: Final = AgentRef("));
    }
}
